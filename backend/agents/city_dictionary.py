def extract_city_by_dictionary(text: str) -> str | None:
    """从任意句子用城市词典做最长匹配，返回命中的城市名；无则 None。

    匹配顺序：在每个连续汉字串里从左到右，优先匹配更长的词典词（4→3→2 字）。
    例如「山西榆次」→「榆次」，「北京挺好的」→「北京」，「火星挺好的」→ None。
    """
    if not text:
        return None
    best: str | None = None
    for match in _CN_RUN_RE.finditer(text):
        run = match.group(0)
        run_len = len(run)
        index = 0
        while index < run_len:
            matched = False
            for size in range(
                min(_CITY_NAME_MAX_CHARS, run_len - index),
                _CITY_NAME_MIN_CHARS - 1,
                -1,
            ):
                token = run[index:index + size]
                if token in CITY_DICTIONARY:
                    if best is None or size > len(best):
                        best = token
                    index += size
                    matched = True
                    break
            if not matched:
                index += 1
    return best
